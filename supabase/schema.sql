--   sesiones_combustible, intentos_login_combustible      -> sesiones y anti fuerza bruta
--   auditoria_combustible  -> bitácora INMUTABLE
--   suscripciones_push     -> dispositivos que reciben notificaciones
-- Los soportes (PDF/imagen) van a Supabase Storage (bucket "soportes").
